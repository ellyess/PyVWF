"""Regenerate the CI constraints files, one per pinned Python version.

The test matrix installs `.[dev]` from `pyproject.toml` with one of these files
as a pip constraint, so a CI result depends on the repository rather than on
whatever PyPI released that morning. The files are resolved per Python version
because the stack splits across a major version: Python 3.10 resolves pandas 2
and 3.11 and 3.12 resolve pandas 3, and both halves have caught real
breakages. The jobs that install other extras get files of their own
(``JOBS``): the extras job and the docs build. The Python 3.13 cell and the
clean-wheel package job stay unpinned on purpose, so a new release still
reaches CI before the files are refreshed, and the wheel is installed as a
user would install it.

    python scripts/dev/lock.py            # rewrite every file
    python scripts/dev/lock.py --check    # exit 1 if a file would change

Needs `uv`. Resolves for Linux x86-64, the CI runners' platform.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "constraints"

#: The Python versions CI runs pinned. tests/test_constraints.py checks that
#: the workflow's pinned cells and these files agree.
PINNED = ("3.10", "3.11", "3.12")

#: Other pinned jobs: file stem -> (Python version, extras). Checked against
#: the workflow by tests/test_constraints.py.
JOBS = {
    "py312-extras": ("3.12", ("dev", "pinn", "data", "parallel")),
    "py312-docs": ("3.12", ("docs",)),
}

HEADER = """\
# Constraints for the CI test matrix on Python {version}: `.[dev]` resolved for
# Linux x86-64. Generated by `python scripts/dev/lock.py`; do not edit by hand.
# Used as `pip install -e ".[dev]" -c constraints/{name}`.
"""

JOB_HEADER = """\
# Constraints for the CI job installing `.[{extras}]` on Python {version}, resolved
# for Linux x86-64. Generated by `python scripts/dev/lock.py`; do not edit by
# hand. Used as `pip install -e ".[{extras}]" -c constraints/{name}`.
"""


def path_for(version: str) -> Path:
    return OUT / f"py{version.replace('.', '')}.txt"


def job_path(stem: str) -> Path:
    return OUT / f"{stem}.txt"


def _compile(version: str, extras: tuple[str, ...], constraint: Path | None = None) -> str:
    """``uv pip compile`` of pyproject.toml with these extras, for Linux x86-64.

    With ``constraint``, every package the test matrix's file already pins keeps
    that version, so a job file adds packages rather than moving shared ones.
    """
    extra_args = [arg for extra in extras for arg in ("--extra", extra)]
    if constraint is not None:
        # Relative to ROOT, where uv runs: uv splits a path on its spaces.
        extra_args += ["--constraint", str(constraint.relative_to(ROOT))]
    return subprocess.run(
        [
            "uv",
            "pip",
            "compile",
            "pyproject.toml",
            *extra_args,
            "--python-version",
            version,
            "--python-platform",
            "x86_64-unknown-linux-gnu",
            "--no-header",
            "--quiet",
        ],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
    ).stdout


def resolve(version: str) -> str:
    """The test-matrix constraints text for one Python version, header included."""
    return HEADER.format(version=version, name=path_for(version).name) + _compile(version, ("dev",))


def resolve_job(stem: str) -> str:
    """The constraints text for one entry of ``JOBS``, header included."""
    version, extras = JOBS[stem]
    header = JOB_HEADER.format(extras=",".join(extras), version=version, name=job_path(stem).name)
    return header + _compile(version, extras, constraint=path_for(version))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="report drift, write nothing")
    args = parser.parse_args(argv)

    OUT.mkdir(exist_ok=True)
    stale = []
    targets = [(path_for(v), lambda v=v: resolve(v)) for v in PINNED]
    targets += [(job_path(stem), lambda stem=stem: resolve_job(stem)) for stem in JOBS]
    for target, build in targets:
        text = build()
        if args.check:
            if not target.is_file() or target.read_text() != text:
                stale.append(target.name)
        else:
            target.write_text(text)
            print(f"wrote {target.relative_to(ROOT)}")
    if stale:
        print(f"out of date: {', '.join(stale)}; run python scripts/dev/lock.py")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
